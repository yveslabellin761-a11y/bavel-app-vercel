-- 8. TÂCHES PLANIFIÉES ET AUTOMATISATIONS (EXTENSION pg_cron)
-- ============================================================================

-- 8.1 Activer pg_cron dans la base de données
CREATE EXTENSION IF NOT EXISTS pg_cron WITH SCHEMA extensions;

-- 8.2 Tâche 1 : Réinitialisation du compteur de likes à minuit pour tous les niveaux (Freemium, Extra, Premium)
SELECT cron.schedule(
  'reset-compteurs-tous-niveaux',
  '0 0 * * *', -- Chaque nuit à minuit pile
  $$ UPDATE public.profiles SET daily_likes_count = 0; $$
);

-- 8.3 Tâche 2 : Nettoyage automatique de l'historique des vieux swipes / rejetés (Sécurité anti-triche & allègement)
SELECT cron.schedule(
  'nettoyer-historique-swipes',
  '0 2 * * *', -- S'exécute toutes les nuits à 2h du matin
  $$ 
    DELETE FROM public.swipes 
    WHERE created_at < now() - interval '24 hours' 
      AND (is_match = false OR is_match IS NULL); 
  $$
);

-- 8.4 Tâche 3 : Purge des comptes non activés / e-mails non confirmés (+ de 7 jours)
SELECT cron.schedule(
  'nettoyage-comptes-non-actives',
  '0 3 * * *',
  $$ DELETE FROM auth.users WHERE email_confirmed_at IS NULL AND created_at < now() - interval '7 days'; $$
);

